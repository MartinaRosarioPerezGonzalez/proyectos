def get_page_count_from_bytes(pdf_bytes: bytes, dpi: int = 72) -> int:
    """Return the number of pages in a PDF without full conversion."""
    try:
        doc = fitz.open(stream=pdf_bytes, filetype="pdf")
        count = len(doc)
        doc.close()
        return count
    except Exception:
        return 0
